func TestSM4_Gcm_RoundTrip(t *testing.T) {
	key, err := GenerateKey()
	if err != nil {
		t.Fatalf("GenerateKey failed: %v", err)
	}
	plain := []byte("Hello, 這是国密SM4測試數據")

	encrypted, err := EncryptGcm(key, plain, false)
	if err != nil {
		t.Fatalf("EncryptGcm failed: %v", err)
	}

	decrypted, err := DecryptGcm(key, encrypted)
	if err != nil {
		t.Fatalf("DecryptGcm failed: %v", err)
	}

	if !bytes.Equal(decrypted, plain) {
		t.Fatalf("decrypted mismatch: got %s want %s", decrypted, plain)
	}
}

