func TestSM4_Gcm_WithSpecificIV(t *testing.T) {
	key, _ := hex.DecodeString("0123456789abcdeffedcba9876543210")
	iv := make([]byte, 12)
	for i := range iv {
		iv[i] = byte(i)
	}
	plain := []byte("Hello, 這是国密SM4測試數據")

	encrypted1, err := EncryptGcmWithIV(key, plain, iv, false)
	if err != nil {
		t.Fatalf("EncryptGcmWithIV failed: %v", err)
	}
	encrypted2, err := EncryptGcmWithIV(key, plain, iv, false)
	if err != nil {
		t.Fatalf("EncryptGcmWithIV failed: %v", err)
	}

	// Same key + IV should produce same ciphertext
	if encrypted1 != encrypted2 {
		t.Fatalf("deterministic encryption mismatch:\n  %s\n  %s", encrypted1, encrypted2)
	}

	decrypted, err := DecryptGcm(key, encrypted1)
	if err != nil {
		t.Fatalf("DecryptGcm failed: %v", err)
	}
	if !bytes.Equal(decrypted, plain) {
		t.Fatalf("decrypted mismatch")
	}
}

func TestSM4_Gcm_TamperDetection(t *testing.T) {
	key, _ := hex.DecodeString("0123456789abcdeffedcba9876543210")
	plain := []byte("Hello, 這是国密SM4測試數據")

	encrypted, err := EncryptGcm(key, plain, false)
	if err != nil {
		t.Fatalf("EncryptGcm failed: %v", err)
	}

	// Tamper with the ciphertext
	tampered := encrypted[:len(encrypted)-2] + "XX"
	_, err = DecryptGcm(key, tampered)
	if err == nil {
		t.Fatal("expected decryption to fail with tampered ciphertext, but it succeeded")
	}
}

// ========================
// SM4 GCM Java interoperability test
// ========================

// Test vector generated by Java SM4Util.encryptGcmNative with:
//   key (hex)  = 0123456789abcdeffedcba9876543210
//   IV (hex)   = 000102030405060708090a0b
//   plaintext  = "Hello, 這是国密SM4測試數據"
//   output     = Base64(IV + ciphertext + Tag)
//   Java result: AAECAwQFBgcICQoLHUR0/d6difbkGWUzdLn96G1Wr/4NZVgH6lwAiXZ4q53any/1ebT8w7FURBOKOUB3W+c=
func TestSM4_Gcm_JavaInterop(t *testing.T) {
	key, _ := hex.DecodeString("0123456789abcdeffedcba9876543210")
	iv, _ := hex.DecodeString("000102030405060708090a0b")
	plain := []byte("Hello, 這是国密SM4測試數據")

	// Encrypt with specific IV, output as Base64 to match Java
	encrypted, err := EncryptGcmWithIV(key, plain, iv, true)
	if err != nil {
		t.Fatalf("EncryptGcmWithIV failed: %v", err)
	}

	const javaCipherBase64 = "AAECAwQFBgcICQoLHUR0/d6difbkGWUzdLn96G1Wr/4NZVgH6lwAiXZ4q53any/1ebT8w7FURBOKOUB3W+c="
	if encrypted != javaCipherBase64 {
		t.Fatalf("Go ciphertext does not match Java:\n  Go:   %s\n  Java: %s", encrypted, javaCipherBase64)
	}

	// Decrypt Java ciphertext (auto-detect Base64)
	decrypted, err := DecryptGcm(key, javaCipherBase64)
	if err != nil {
		t.Fatalf("DecryptGcm of Java ciphertext failed: %v", err)
	}
	if !bytes.Equal(decrypted, plain) {
		t.Fatalf("decrypted mismatch: got %s want %s", decrypted, plain)
	}
}

