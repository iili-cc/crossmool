package cc.iili.tools.crossmool.interop;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;

import cc.iili.tools.crossmool.tool.SM2Util;
import cc.iili.tools.crossmool.tool.SM3Util;
import cc.iili.tools.crossmool.tool.SM4Util;
import cc.iili.tools.crossmool.util.HexUtil;

/**
 * Java interoperability test class - used to verify consistency between Java and C++ implementations.
 */
public class InteropTest {

    public static void main(String[] args) {
        try {
            System.out.println("Starting Java-C++ interoperability test...");

            // Verify against interop test data generated by C++ if it exists
            testCppGeneratedData();

            // Run basic tests on the Java side
            runBasicTests();

            System.out.println("Java-C++ interoperability test completed!");
        } catch (Exception e) {
            System.err.println("Test failed: " + e.getMessage());
            e.printStackTrace();
        }
    }

    private static void testCppGeneratedData() throws Exception {
        // Try to read data files generated by the C++ test program
        try {
            String pubDerPath = "interop_test_public.der";
            String privDerPath = "interop_test_private.der";
            String cipherPath = "interop_test_cipher.hex";
            String sigPath = "interop_test_signature.hex";

            // Read public and private key DER files
            byte[] pubKeyDer = Files.readAllBytes(Paths.get(pubDerPath));
            byte[] privKeyDer = Files.readAllBytes(Paths.get(privDerPath));

            // Read ciphertext and signature
            String cipherHex = Files.readString(Paths.get(cipherPath)).trim();
            String sigHex = Files.readString(Paths.get(sigPath)).trim();

            String message = "interoperability-test-message";

            // Verify on the Java side whether the ciphertext generated by C++ can be correctly decrypted by Java
            String privKeyHex = HexUtil.encodeHexStr(privKeyDer);
            String decryptedMsg = SM2Util.decrypt(cipherHex, privKeyHex);
            if (!message.equals(decryptedMsg)) {
                System.err.println("C++ generated ciphertext failed to decrypt in Java!");
                System.err.println("Expected: " + message);
                System.err.println("Actual: " + decryptedMsg);
            } else {
                System.out.println("✓ C++ generated ciphertext decrypted in Java: " + decryptedMsg);
            }

            // Verify on the Java side whether the signature generated by C++ can be correctly verified by Java
            String pubKeyHex = HexUtil.encodeHexStr(pubKeyDer);
            boolean isValid = SM2Util.verify(message, pubKeyHex, sigHex);
            if (!isValid) {
                System.err.println("C++ generated signature failed to verify in Java!");
            } else {
                System.out.println("✓ C++ generated signature verified in Java");
            }

            // Re-encrypt and re-sign with Java to see whether C++ can decrypt and verify
            String javaCipherHex = SM2Util.encryptToHex(message, pubKeyHex);
            System.out.println("✓ Java re-encryption succeeded, result saved as hex");

            String javaSigHex = SM2Util.signToHex(message, privKeyHex);
            System.out.println("✓ Java re-signing succeeded, result saved as hex");

        } catch (Exception e) {
            System.out.println("Note: no C++ interop test data file found, this may be normal (first run)");
        }
    }

    private static void runBasicTests() throws Exception {
        System.out.println("Running Java basic function tests...");

        // SM2 tests
        System.out.println("Testing SM2...");
        String message = "test message for SM2";
        var keyPair = SM2Util.generateKeyPairBase64();

        String encrypted = SM2Util.encrypt(message, keyPair.getPublicKey());
        String decrypted = SM2Util.decrypt(encrypted, keyPair.getPrivateKey());
        if (message.equals(decrypted)) {
            System.out.println("✓ SM2 encrypt/decrypt succeeded");
        } else {
            System.err.println("✗ SM2 encrypt/decrypt failed");
        }

        String signature = SM2Util.sign(message, keyPair.getPrivateKey());
        boolean verified = SM2Util.verify(message, keyPair.getPublicKey(), signature);
        if (verified) {
            System.out.println("✓ SM2 sign/verify succeeded");
        } else {
            System.err.println("✗ SM2 sign/verify failed");
        }

        // SM3 tests
        System.out.println("Testing SM3...");
        String sm3Result = SM3Util.digestToStr(message);
        if (sm3Result.length() == 64) { // 32 bytes = 64 hex chars
            System.out.println("✓ SM3 hash succeeded: " + sm3Result.substring(0, 10) + "...");
        } else {
            System.err.println("✗ SM3 hash failed");
        }

        // SM4 GCM tests
        System.out.println("Testing SM4 GCM...");
        String sm4Key = SM4Util.generateKeyAsHex();
        String sm4Encrypted = SM4Util.encryptGcmNative(message.getBytes(StandardCharsets.UTF_8), SM4Util.parseHexKey(sm4Key));
        String sm4Decrypted = SM4Util.decryptGcmNativeToString(sm4Encrypted, SM4Util.parseHexKey(sm4Key));

        if (message.equals(sm4Decrypted)) {
            System.out.println("✓ SM4 GCM encrypt/decrypt succeeded");
        } else {
            System.err.println("✗ SM4 GCM encrypt/decrypt failed");
        }

        System.out.println("Java basic function tests completed!");
    }
}
